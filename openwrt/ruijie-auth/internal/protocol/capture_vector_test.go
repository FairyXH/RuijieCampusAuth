func captureNetwork() NetworkInfo {
	return NetworkInfo{
		IP:       "172.18.28.6",
		Netmask:  "255.255.128.0",
		Gateway:  "172.18.0.1",
		DHCP:     "172.18.0.1",
		IPString: "172.18.28.6",
		StaticID: []byte(captureStaticID),
	}
}

func captureTail(t *testing.T, iv []byte, nonce, fingerprint string) []byte {
	t.Helper()
	service, err := GB18030Encode(captureService)
	if err != nil {
		t.Fatalf("encode service: %v", err)
	}
	tail, err := BuildTail(
		[]byte(captureUser),
		[]byte(capturePassword),
		captureMAC,
		captureNetwork(),
		iv,
		&TailOptions{
			HeaderFlag:  1,
			Nonce:       []byte(nonce),
			Fingerprint: []byte(fingerprint),
			ServiceName: service,
		})
	if err != nil {
		t.Fatalf("BuildTail: %v", err)
	}
	return tail
}

func TestBuildTailMatchesCapturedStart(t *testing.T) {
	want, err := hex.DecodeString(captureStartTailHex)
	if err != nil {
		t.Fatalf("decode vector: %v", err)
	}
	got := captureTail(t, make([]byte, 16), identityNonce, string(make([]byte, 128)))
	if len(got) != len(want) {
		t.Fatalf("length = %d, want %d", len(got), len(want))
	}
	if hex.EncodeToString(got) != hex.EncodeToString(want) {
		for i := range want {
			if got[i] != want[i] {
				t.Fatalf("first mismatch at byte %d: got %02x want %02x", i, got[i], want[i])
			}
		}
	}
}

